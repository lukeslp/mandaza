private data class DrawableLoop(
    val prepared: PreparedLoop,
    val completePath: Path,
)

/**
 * TV canvas — same engine as phone Mandaza, no tilt/audio coupling.
 * Kept in the tv module for now; consolidate with app MandazaCanvas later.
 */
@Composable
fun MandazaCanvas(
    seed: String,
    paletteId: String,
    config: EngineConfig,
    canvasWidth: Float,
    canvasHeight: Float,
    paperTheme: Boolean,
    modifier: Modifier = Modifier,
) {
    val renderSize = remember(canvasWidth, canvasHeight) {
        resolveTvRenderSize(canvasWidth, canvasHeight)
    }
    val generated by produceState<GeneratedMandaza?>(
        initialValue = null,
        seed, config, renderSize,
    ) {
        value = withContext(Dispatchers.Default) {
            MandazaEngine(config).generate(
                renderSize.width.toDouble(),
                renderSize.height.toDouble(),
                seed,
            )
        }
    }
    val drawableLoops = remember(generated) {
        generated?.loops.orEmpty().map { loop ->
            val prepared = prepareLoop(loop)
            DrawableLoop(prepared, pathFor(loop.curves))
        }
    }
    var elapsedMs by remember(generated) { mutableDoubleStateOf(0.0) }
    val renderSpeed = config.drawSpeed.coerceAtLeast(0.45)
    val revealDuration = remember(drawableLoops, renderSpeed) {
        revealDurationMs(
            totalLength = drawableLoops.maxOfOrNull { it.prepared.totalLength } ?: 0.0,
            drawSpeed = renderSpeed,
        )
    }
    LaunchedEffect(generated, revealDuration) {
        var previous = 0L
        while (isActive && elapsedMs < revealDuration) {
            withFrameNanos { now ->
                if (previous != 0L) {
                    val frameMs = (now - previous) / 1_000_000.0
                    elapsedMs = (elapsedMs + boundedTvFrameMs(frameMs))
                        .coerceAtMost(revealDuration)
                }
                previous = now
            }
        }
    }
    val ground = if (paperTheme) Color(0xFFF1E6CF) else Color.Black
    val palette = remember(paletteId) { MandazaPalettes.byId(paletteId) }
    val colors = remember(drawableLoops, paletteId, paperTheme) {
        drawableLoops.map { drawable ->
            val loop = drawable.prepared.source
            val position =
                if (loop.colorTotal > 1) loop.colorIndex.toDouble() / (loop.colorTotal - 1) else 0.5
            val color = Color(palette.colorAt(position).toInt())
            if (paperTheme) color.copy(alpha = 0.86f) else color
        }
    }

    Canvas(modifier = modifier) {
        drawRect(ground)
        val art = generated ?: return@Canvas
        val drawDistance = drawDistanceAt(elapsedMs, renderSpeed)
        val baseWidth = (art.radius / 30 * config.lineWidth).toFloat().coerceAtLeast(1f)
        val stroke = Stroke(
            width = baseWidth,
            cap = StrokeCap.Round,
            join = StrokeJoin.Round,
        )
        withTransform({
            scale(
                scaleX = size.width / art.width.toFloat(),
                scaleY = size.height / art.height.toFloat(),
            )
        }) {
            drawableLoops.forEachIndexed { index, drawable ->
                val prepared = drawable.prepared
                val path = if (drawDistance >= prepared.totalLength) {
                    drawable.completePath
                } else {
                    val cubics = visibleCubics(prepared, drawDistance)
                    if (cubics.isEmpty()) return@forEachIndexed
                    pathFor(cubics)
                }
                drawPath(path, colors[index], style = stroke)
            }
        }
    }
}

private fun pathFor(cubics: List<MandazaCubic>): Path {
    val path = Path()
    cubics.forEachIndexed { index, curve ->
        if (index == 0) path.moveTo(curve.start.x.toFloat(), curve.start.y.toFloat())
        path.cubicTo(
            curve.control1.x.toFloat(), curve.control1.y.toFloat(),
            curve.control2.x.toFloat(), curve.control2.y.toFloat(),
            curve.end.x.toFloat(), curve.end.y.toFloat(),
        )
    }
    return path
}
